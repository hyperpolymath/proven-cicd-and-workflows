# advisory-autofix-dependabot.sh — print a .github/dependabot.yml (KYAML) with
# one `cargo` entry per Cargo workspace directory in the tree, found by the
# same rule the auto-fix uses (advisory-autofix-discover.sh). Run it from the
# repository root and commit the output; rerun when a workspace is added.
#
# SECURITY-ONLY. `open-pull-requests-limit: 0` stops version-update PRs while
# Dependabot SECURITY updates (which have their own limit) still open. Do NOT
# add an `ignore: update-types: [version-update:semver-patch]` rule: it would
# block exactly the patch-level security PRs this exists for.
#
# The owner must also switch on "Dependabot security updates" in the repo's
# settings (Code security); no file can do that. Exit 2 when there is no
# Cargo workspace: an empty updates list would be a config that proves nothing.
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
mapfile -t dirs < <(bash "$here/advisory-autofix-discover.sh" "${1:-.}")
[ "${#dirs[@]}" -gt 0 ] || { echo "no Cargo workspace found; no dependabot.yml generated" >&2; exit 2; }
cat <<'HDR'
# SPDX-License-Identifier: MPL-2.0
# Dependabot SECURITY updates for every Cargo workspace (KYAML). Generated by
# proven-cicd-and-workflows scripts/advisory-autofix-dependabot.sh; rerun it
# when a workspace is added. `open-pull-requests-limit: 0` = security PRs only.
{
  version: 2,
  updates: [
HDR
for d in "${dirs[@]}"; do
  if [ "$d" = . ]; then dir="/"; else dir="/$d"; fi
  cat <<ENT
    {
      package-ecosystem: "cargo",
      directory: "$dir",
      schedule: { interval: "weekly" },
      open-pull-requests-limit: 0,
    },
ENT
done
printf '  ],\n}\n'
