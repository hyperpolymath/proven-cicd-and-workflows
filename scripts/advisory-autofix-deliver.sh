#!/usr/bin/env bash
# SPDX-License-Identifier: MPL-2.0
#
# advisory-autofix-deliver.sh — turn advisory-autofix-fix.sh's report into
# GitHub objects: ONE signed draft-free PR for the bumped lockfiles, and ONE
# issue per advisory that cannot be fixed automatically.
#
# SIGNING. The commit is made with the GraphQL `createCommitOnBranch`
# mutation, which GitHub itself signs (Verified) when the caller's token is a
# GitHub App or user token. No git identity or key lives on the runner.
#
# NEVER AUTO-MERGE. This script opens the PR and stops. It never calls the
# merge or auto-merge APIs; the owner merges.
#
# TOKEN. A PR created with the workflow's own GITHUB_TOKEN does NOT start
# other workflows, so the repo's full CI and proof lanes would never run on it
# and "green" would mean nothing. Pushes therefore need AUTOFIX_TOKEN (an App
# or fine-grained token: contents, pull-requests, issues write). Without it
# and with a bump to deliver this exits 1 and says why, rather than open a PR
# nobody tested. Issues need no special token (GITHUB_TOKEN may open them).
#
# Environment: REPORT, GH_REPO (owner/name), BASE_BRANCH, AUTOFIX_TOKEN,
# GITHUB_TOKEN, RUN_URL, DRY_RUN=1 (print, change nothing; used by the tests).
set -euo pipefail
REPORT="${REPORT:-advisory-autofix-report.json}"
: "${GH_REPO:?GH_REPO (owner/name) is required}"
BASE_BRANCH="${BASE_BRANCH:-$(git symbolic-ref --short refs/remotes/origin/HEAD 2>/dev/null | sed 's#^origin/##' || echo main)}"
BRANCH="advisory-autofix"
run="${RUN_URL:-}"
say() { echo "advisory-autofix-deliver: $*" >&2; }
gh_() { if [ "${DRY_RUN:-}" = 1 ]; then echo "DRY: gh $*" >&2; return 0; fi; gh "$@"; }

# ---- issues: ONE per (advisory, crate) across ALL workspaces, opened or
# updated, never duplicated. The same advisory in several workspaces is one
# issue that lists every affected workspace, version and reason; otherwise each
# workspace would overwrite the issue body with its own.
jq -c '[.workspaces[] | .dir as $d | .issues[] | {id, crate, version, reason, dir: $d}]
       | group_by([.id, .crate])[]
       | {id: .[0].id, crate: .[0].crate, items: (map({dir, version, reason}) | unique)}' "$REPORT" |
while IFS= read -r grp; do
  id="$(jq -r .id <<<"$grp")"; crate="$(jq -r .crate <<<"$grp")"
  title="advisory-autofix: $id in $crate has no automatic fix"
  affected="$(jq -r '.items[] | "- workspace `\(.dir)`: `\(.version)` — \(.reason)"' <<<"$grp")"
  body="$(printf '%s\n' \
"<!-- advisory-autofix:$id:$crate -->" \
"**$id** affects \`$crate\` and cannot be fixed automatically in:" \
"" \
"$affected" \
"" \
"Advisory: https://rustsec.org/advisories/$id" \
"" \
"This issue is updated by the scheduled advisory auto-fix while the advisory persists${run:+ (latest run: $run)}. It needs an owner decision: wait for a patch, change the manifest, replace the crate, or an owner-authored \`deny.toml\` ignore with a reason." \
"" "---" "_Generated by advisory-autofix (proven-cicd-and-workflows)_")"
  existing=""
  if [ "${DRY_RUN:-}" != 1 ]; then
    existing="$(GH_TOKEN="${GITHUB_TOKEN:-}" gh issue list --repo "$GH_REPO" --state open --search "\"advisory-autofix: $id in $crate\" in:title" --json number,title --jq ".[] | select(.title==\"$title\") | .number" | head -n1)"
  fi
  if [ -n "$existing" ]; then
    say "updating issue #$existing ($id $crate)"
    GH_TOKEN="${GITHUB_TOKEN:-}" gh_ issue edit "$existing" --repo "$GH_REPO" --body "$body"
  else
    say "opening issue: $title"
    GH_TOKEN="${GITHUB_TOKEN:-}" gh_ issue create --repo "$GH_REPO" --title "$title" --body "$body"
  fi
done

# ---- PR: bumped lockfiles
nchanged="$(jq '.changed|length' "$REPORT")"
if [ "$nchanged" -eq 0 ]; then say "no lockfile changed; no PR"; exit 0; fi
if [ -z "${AUTOFIX_TOKEN:-}" ] && [ "${DRY_RUN:-}" != 1 ]; then
  echo "::error::$nchanged lockfile(s) have fixes but no AUTOFIX_TOKEN secret was passed. A PR from GITHUB_TOKEN starts no CI or proof lanes, so it could not be green. Add the secret (see templates/advisory-autofix-caller.yml). Nothing was pushed." >&2
  exit 1
fi
export GH_TOKEN="${AUTOFIX_TOKEN:-dry}"
# The lockfiles were produced from THIS checkout. Publish them on exactly this
# commit, and refuse if the default branch has moved since the audit: putting
# older lockfiles on a newer base would silently revert whatever changed.
# (expectedHeadOid below guards the bot branch, not this.)
base_oid="$(git rev-parse HEAD)"
if [ "${DRY_RUN:-}" != 1 ]; then
  current="$(gh api "repos/$GH_REPO/git/ref/heads/$BASE_BRANCH" --jq .object.sha)"
  if [ "$current" != "$base_oid" ]; then
    echo "::error::$BASE_BRANCH moved from the audited $base_oid to $current during the run; the lockfiles are NOT published. Rerun the workflow." >&2
    exit 1
  fi
fi

# Idempotence: reuse the bot branch only if it is EXACTLY the intended change:
# one commit on top of the audited base, touching exactly the lockfiles in this
# report, with exactly their contents. A branch with extra stale changes from an
# earlier run, or built on an older base, is rebuilt from the audited base.
same=1
if [ "${DRY_RUN:-}" = 1 ]; then
  same=0
else
  cmp_json="$(gh api "repos/$GH_REPO/compare/$base_oid...$BRANCH" 2>/dev/null || true)"
  want="$(jq -r '.changed[] | ltrimstr("./")' "$REPORT" | sort)"
  have_files="$(jq -r '.files[]?.filename' <<<"${cmp_json:-null}" 2>/dev/null | sort || true)"
  if [ -z "$cmp_json" ] \
     || [ "$(jq -r '.ahead_by // -1' <<<"$cmp_json" 2>/dev/null)" != 1 ] \
     || [ "$(jq -r '.behind_by // -1' <<<"$cmp_json" 2>/dev/null)" != 0 ] \
     || [ "$want" != "$have_files" ]; then
    same=0
  else
    while IFS= read -r p; do
      have="$(gh api "repos/$GH_REPO/contents/${p#./}?ref=$BRANCH" --jq .content 2>/dev/null | tr -d '\n' || true)"
      [ -n "$have" ] && [ "$have" = "$(base64 -w0 "$p")" ] || { same=0; break; }
    done < <(jq -r '.changed[]' "$REPORT")
  fi
fi
if [ "$same" = 1 ]; then say "branch $BRANCH already carries these lockfiles; skipping the branch and commit, checking the PR"; fi

if [ "$same" != 1 ]; then
# (Re)point the bot's own branch at the base, then add ONE signed commit.
if gh_ api "repos/$GH_REPO/git/ref/heads/$BRANCH" >/dev/null 2>&1; then
  gh_ api -X PATCH "repos/$GH_REPO/git/refs/heads/$BRANCH" -f sha="$base_oid" -F force=true >/dev/null
else
  gh_ api -X POST "repos/$GH_REPO/git/refs" -f ref="refs/heads/$BRANCH" -f sha="$base_oid" >/dev/null
fi
summary="$(jq -r '[.workspaces[] | .dir as $d | .bumped[] | "\(.crate) \(.from) -> \(.to) (\(.id), \($d))"] | join("; ")' "$REPORT")"
additions="$(jq -n '[]')"
while IFS= read -r p; do
  additions="$(jq -c --arg p "${p#./}" --arg c "$(base64 -w0 "$p")" '. + [{path:$p, contents:$c}]' <<<"$additions")"
done < <(jq -r '.changed[]' "$REPORT")
vars="$(jq -n --arg repo "$GH_REPO" --arg br "$BRANCH" --arg oid "$base_oid" --arg h "advisory-autofix: bump to patched versions" \
  --arg b "$summary" --argjson add "$additions" \
  '{input:{branch:{repositoryNameWithOwner:$repo,branchName:$br},message:{headline:$h,body:$b},expectedHeadOid:$oid,fileChanges:{additions:$add}}}')"
gh_ api graphql --input - <<<"$(jq -n --argjson v "$vars" '{query:"mutation($input:CreateCommitOnBranchInput!){createCommitOnBranch(input:$input){commit{oid}}}",variables:$v}')" >/dev/null
fi

# Which proof lanes does this repo declare? Listed so the owner can see what
# must be green; the PR cannot enforce them (branch protection does).
lanes="$(grep -rlE 'creusot|verus|kani|aeneas' .github/workflows 2>/dev/null | sed 's#^#- `#; s#$#`#' | sort -u || true)"
pr_body="$(printf '%s\n' \
"Bumps vulnerable dependencies to the **lowest patched version** with \`cargo update -p <crate> --precise <version>\`:" \
"" "$(jq -r '.workspaces[] | .dir as $d | .bumped[] | "- `\(.crate)` \(.from) → \(.to) — \(.id) (workspace `\($d)`)"' "$REPORT")" \
"" "**Not auto-merged. The owner merges.** Merge only when the repo's full CI is green **and** its declared proof lanes (Creusot with Pearlite and Verus for first-party Rust; Kani and Aeneas where declared) have passed. A bump can break a proof; a verifier failure must be fixed, never skipped, silenced or retried into green." \
"" "Workflows in this repo that mention a proof lane:" "${lanes:-- none found: this repository declares no proof lane}" \
"" "Run: ${run:-n/a}" "" "---" "_Generated by advisory-autofix (proven-cicd-and-workflows)_")"
if gh_ pr list --repo "$GH_REPO" --head "$BRANCH" --state open --json number --jq '.[0].number' 2>/dev/null | grep -q .; then
  say "open PR for $BRANCH already exists; its branch was updated in place"
else
  gh_ pr create --repo "$GH_REPO" --base "$BASE_BRANCH" --head "$BRANCH" --title "advisory-autofix: bump to patched versions" --body "$pr_body"
fi
